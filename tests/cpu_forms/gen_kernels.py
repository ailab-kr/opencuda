#!/usr/bin/env python3
"""Random race-free kernels without synchronisation points, for the two kernel
forms of the CPU path (docs/cpu-region-loops.md, test item 13).

    gen_kernels.py <seed> <count> <out.cu>

Each kernel is one thread-pure function `body_N(tid, bid, bdim, arg, &res)`
(unsigned arithmetic only, no undefined behaviour) with uniform and
per-thread `if`s, bounded loops, early returns (also inside loops), a local
array and calls to a helper. The kernel gives every thread its own output
slot, so there are no races. The same function is compiled for the host and
the program checks every thread's result against it, and prints a hash per
kernel and block shape, so both forms are compared by the driver too.
"""
import random
import sys

seed = int(sys.argv[1])
count = int(sys.argv[2])
out = sys.argv[3]
rnd = random.Random(seed)

VARS = ["v0", "v1", "v2", "v3"]
ATOMS = ["tid", "bid", "bdim", "arg"]


def const():
    return str(rnd.choice([0, 1, 2, 3, 5, 7, 13, 31, 255, 1000, 65599, 0x9E3779B1, 0xFFFFFFFF])) + "u"


def expr(depth=0):
    r = rnd.random()
    if depth > 2 or r < 0.30:
        return rnd.choice(VARS + ATOMS + [const()])
    if r < 0.40:
        return "la[(%s) & 7u]" % expr(depth + 1)
    if r < 0.50:
        return "h%d(%s, %s)" % (rnd.randrange(2), expr(depth + 1), expr(depth + 1))
    op = rnd.choice(["+", "-", "*", "^", "&", "|", "<<", ">>"])
    a, b = expr(depth + 1), expr(depth + 1)
    if op in ("<<", ">>"):
        return "((%s) %s ((%s) & 31u))" % (a, op, b)
    return "((%s) %s (%s))" % (a, op, b)


def cond():
    r = rnd.random()
    if r < 0.3:
        # uniform: the same for every thread of the launch (arg) or of the block (bid, bdim)
        return "(%s) %s (%s)" % (rnd.choice(["arg", "bdim", "bid", "arg ^ bid"]), rnd.choice(["<", ">", "==", "!="]),
                                 rnd.choice(["3u", "50u", "1000u", "bdim", "arg"]))
    return "(%s) %s (%s)" % (expr(1), rnd.choice(["<", ">", "==", "!=", "<=", ">="]), expr(1))


def block(depth, indent, in_loop):
    lines = []
    n = rnd.randint(1, 4 if depth == 0 else 3)
    pad = "    " * indent
    for _ in range(n):
        r = rnd.random()
        if r < 0.35 or depth >= 3:
            lines.append("%s%s = %s;" % (pad, rnd.choice(VARS), expr()))
        elif r < 0.45:
            lines.append("%sla[(%s) & 7u] = %s;" % (pad, expr(1), expr()))
        elif r < 0.65:
            lines.append("%sif (%s) {" % (pad, cond()))
            lines += block(depth + 1, indent + 1, in_loop)
            if rnd.random() < 0.5:
                lines.append("%s} else {" % pad)
                lines += block(depth + 1, indent + 1, in_loop)
            lines.append("%s}" % pad)
        elif r < 0.85:
            iv = "i%d" % depth
            bound = rnd.choice(["%du" % rnd.randint(1, 6), "((tid ^ bid) & 3u) + 1u", "(arg & 3u) + 2u"])
            lines.append("%sfor (unsigned %s = 0; %s < %s; ++%s) {" % (pad, iv, iv, bound, iv))
            lines.append("%s    v%d += %s;" % (pad, rnd.randrange(4), iv))
            lines += block(depth + 1, indent + 1, True)
            lines.append("%s}" % pad)
        else:
            lines.append("%sif (%s) return false;" % (pad, cond()))
    return lines


src = []
src.append("// Generated by gen_kernels.py (seed %d, %d kernels). Do not edit." % (seed, count))
src.append('#include <cuda_runtime.h>')
src.append('#include <cstdint>')
src.append('#include <cstdio>')
src.append('#include <cstring>')
src.append('#include <vector>')
src.append("")
src.append("__host__ __device__ __attribute__((noinline)) static unsigned h0(unsigned a, unsigned b) { return a * 2654435761u + (b ^ (a >> 5)); }")
src.append("__host__ __device__ static unsigned h1(unsigned a, unsigned b) { return (a << 3) ^ (b + 17u) ^ (a >> 11); }")
src.append("")
for k in range(count):
    src.append("__host__ __device__ static bool body_%d(unsigned tid, unsigned bid, unsigned bdim, unsigned arg, unsigned *res)" % k)
    src.append("{")
    src.append("    unsigned v0 = tid + 1u, v1 = bid * 3u + 7u, v2 = arg, v3 = 0x12345u;")
    src.append("    unsigned la[8];")
    src.append("    for (unsigned j = 0; j < 8; ++j) la[j] = j * 41u + tid;")
    src += block(0, 1, False)
    src.append("    unsigned s = v0 * 31u + v1 * 17u + v2 * 7u + v3;")
    src.append("    for (unsigned j = 0; j < 8; ++j) s = s * 33u + la[j];")
    src.append("    *res = s;")
    src.append("    return true;")
    src.append("}")
    src.append("__global__ void gk_%d(unsigned *out, unsigned arg)" % k)
    src.append("{")
    src.append("    unsigned bdim = blockDim.x * blockDim.y * blockDim.z;")
    src.append("    unsigned bid = (blockIdx.z * gridDim.y + blockIdx.y) * gridDim.x + blockIdx.x;")
    src.append("    unsigned tid = (threadIdx.z * blockDim.y + threadIdx.y) * blockDim.x + threadIdx.x;")
    src.append("    unsigned r;")
    src.append("    if (body_%d(tid, bid, bdim, arg, &r)) out[bid * bdim + tid] = r;" % k)
    src.append("}")
    src.append("")

src.append("typedef void (*kern_t)(unsigned *, unsigned);")
src.append("typedef bool (*body_t)(unsigned, unsigned, unsigned, unsigned, unsigned *);")
src.append("static kern_t kernels[] = {" + ", ".join("gk_%d" % k for k in range(count)) + "};")
src.append("static body_t bodies[] = {" + ", ".join("body_%d" % k for k in range(count)) + "};")
src.append(r'''
static int g_fail, g_checks;

struct Shape { dim3 grid, block; };

int main()
{
    Shape shapes[] = {
        {dim3(3), dim3(33)}, {dim3(2), dim3(100)}, {dim3(4), dim3(1)}, {dim3(1), dim3(64)},
        {dim3(2, 2), dim3(5, 3, 2)}, {dim3(2), dim3(1, 1, 40)}, {dim3(1), dim3(32, 4)},
    };
    const unsigned args[] = {7u, 1000u};
    unsigned *d = nullptr;
    cudaMalloc((void **)&d, 4096 * 4);
    uint64_t total = 1469598103934665603ull;
    for (int k = 0; k < (int)(sizeof kernels / sizeof kernels[0]); ++k) {
        uint64_t h = 1469598103934665603ull;
        int bad = 0;
        for (auto &s : shapes) {
            unsigned bdim = s.block.x * s.block.y * s.block.z, nb = s.grid.x * s.grid.y * s.grid.z;
            for (unsigned arg : args) {
                std::vector<unsigned> want(nb * bdim, 0xDEADBEEFu);
                for (unsigned b = 0; b < nb; ++b)
                    for (unsigned t = 0; t < bdim; ++t) {
                        unsigned r;
                        if (bodies[k](t, b, bdim, arg, &r)) want[b * bdim + t] = r;
                    }
                std::vector<unsigned> init(nb * bdim, 0xDEADBEEFu);
                cudaMemcpy(d, init.data(), init.size() * 4, cudaMemcpyHostToDevice);
                kern_t kf = kernels[k];
                kf<<<s.grid, s.block>>>(d, arg);
                cudaDeviceSynchronize();
                std::vector<unsigned> got(nb * bdim);
                cudaMemcpy(got.data(), d, got.size() * 4, cudaMemcpyDeviceToHost);
                ++g_checks;
                if (got != want) { ++bad; ++g_fail; }
                const unsigned char *c = (const unsigned char *)got.data();
                for (size_t i = 0; i < got.size() * 4; ++i) { h ^= c[i]; h *= 1099511628211ull; }
            }
        }
        if (bad) std::printf("FAIL kernel gk_%d: %d launches differ from the host evaluation\n", k, bad);
        std::printf("kernel %d %016llx\n", k, (unsigned long long)h);
        total ^= h;
    }
    cudaFree(d);
    std::printf("generated: %d checks, %d failed, total %016llx\n", g_checks, g_fail, (unsigned long long)total);
    return g_fail ? 1 : 0;
}
''')
open(out, "w").write("\n".join(src) + "\n")
