#!/usr/bin/env python3
"""Generate the log table of runtime/include/ocu_device_math_tables.h.

For i in 0..127, c_i is 1 / (1 + (i + 0.5) / 128) rounded to 12 significant
bits (so it is an exact double), and log(c_i) is computed with exact integer
arithmetic to 160 bits, then split into two doubles (hi + lo). Nothing is
taken from any other library; rerun to check the committed table:

    python3 tools/gen_log_table.py > runtime/include/ocu_device_math_tables.h
"""
from fractions import Fraction
import math

BITS = 200


def ln_fixed(q: Fraction) -> int:
    """ln(q) * 2^BITS for q in (0.5, 2), by ln q = 2 atanh((q - 1) / (q + 1))."""
    y = (q - 1) / (q + 1)
    if y < 0:  # odd function; keep the shifts on non-negative numbers
        return -ln_fixed(1 / q)
    one = 1 << BITS
    ynum = y.numerator * one // y.denominator  # y * 2^BITS (truncated; error < 2^-BITS)
    y2 = ynum * ynum >> BITS
    term = ynum
    total = 0
    k = 1
    while term != 0:
        total += term // k
        term = term * y2 >> BITS
        k += 2
    return 2 * total


def to_double_pair(v: int):
    """v / 2^BITS as hi + lo doubles (hi rounded to nearest, lo the rest)."""
    x = Fraction(v, 1 << BITS)
    hi = float(x)                  # correctly rounded
    lo = float(x - Fraction(hi))
    return hi, lo


def round_sig(x: Fraction, bits: int) -> float:
    if x == 0:
        return 0.0
    e = math.floor(math.log2(x))
    scale = Fraction(2) ** (bits - 1 - e)
    return float(Fraction(round(x * scale)) / scale)


def main():
    print("/* Generated by tools/gen_log_table.py; do not edit. */")
    print("#ifndef OCU_DEVICE_MATH_TABLES_H")
    print("#define OCU_DEVICE_MATH_TABLES_H")
    print("namespace ocu_dm {")
    print("/* c_i ~ 1 / (1 + (i + 0.5) / 128) with 12 significant bits; -log(c_i) = hi + lo */")
    print("struct log_entry { double c, neg_log_hi, neg_log_lo; };")
    print("constexpr log_entry LOG_TABLE[128] = {")
    for i in range(128):
        c = round_sig(1 / (1 + Fraction(2 * i + 1, 256)), 12)
        hi, lo = to_double_pair(-ln_fixed(Fraction(c)))
        print(f"    {{{c.hex()}, {hi.hex()}, {lo.hex()}}},")
    print("};")
    hi, lo = to_double_pair(ln_fixed(Fraction(2)))
    print(f"constexpr double LN2_DD_HI = {hi.hex()}, LN2_DD_LO = {lo.hex()};")
    print("} // namespace ocu_dm")
    print("#endif")


if __name__ == "__main__":
    main()
