#!/usr/bin/env python3
"""ocu-cc (probe): compile one .cu file for the CPU, NVIDIA or AMD path.

PROBE ONLY (PLAN P0-W1-11): a single entry point for the experiments in
this folder, and the starting point of the build-tool work in phase 2. It
is not the nvcc-compatible driver.

    ocu_cc.py --target cpu    -c k.cu -o k.o  [-I dir] [-D NAME[=V]] [-O2] [-g]
    ocu_cc.py --target nvidia --arch sm_80   -c k.cu -o k.ptx
    ocu_cc.py --target amd    --arch gfx1201 -c k.cu -o k.co
    ocu_cc.py ... --print-commands      (show what runs, do not run)

What it guarantees on every path:
  - no vendor SDK file is read: -nocudainc -nocudalib (or -nogpuinc
    -nogpulib) always, and --cuda-path points at a folder of our own whose
    only content is a one-line version marker;
  - include paths that point into a vendor SDK are refused.

cpu:    .cu: preprocess as C++17 with our cuda_runtime.h force-included
        (as nvcc does) and __CUDACC__ defined, rewrite the whole translation
        unit (cpu_rewrite.py: launches in included files and macros too),
        compile the result. .c/.cpp: compile with our headers on the
        include path, as nvcc hands them to the host compiler. Link with
        ocu_cudart (see cmake/OcuCpuPath.cmake).
nvidia: device code only, as PTX (-S).
amd:    device code only, as a code object.
"""

from __future__ import annotations

import argparse
import os
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
VENDOR_MARKERS = ("/usr/local/cuda", "/opt/cuda", "NVIDIA GPU Computing Toolkit",
                  "/opt/rocm/include/hip/amd_detail")  # last: HIP internals, never needed

sys.path.insert(0, str(HERE))
from cpu_rewrite import RewriteError, rewrite  # noqa: E402


def pinned_cuda_path(cache: Path) -> Path:
    """Our own folder: a one-line version marker so clang targets CUDA 12.3
    (newer launch ABI, PTX 8.3). Nothing else in it is read."""
    root = cache / "ocu-cuda-path"
    (root / "include").mkdir(parents=True, exist_ok=True)
    for sub in ("bin", "lib64"):
        (root / sub).mkdir(exist_ok=True)
    marker = root / "include" / "cuda.h"
    text = "/* version marker only, generated by ocu_cc.py */\n#define CUDA_VERSION 12030\n"
    if not marker.exists() or marker.read_text() != text:
        # Write then rename: concurrent runs never see a half-written file.
        tmp = marker.with_name(f".cuda.h.{os.getpid()}")
        tmp.write_text(text)
        os.replace(tmp, marker)
    return root


def _llvm_tool(name: str) -> str:
    for v in (20, 19, 18):
        p = Path(f"/usr/lib/llvm-{v}/bin/{name}")
        if p.exists():
            return str(p)
    return name


def macos_sdk_env(env: dict) -> dict:
    """On macOS, a compiler called by full path (not through xcrun) does not
    find the SDK by itself. Set SDKROOT for it (unless already set): unlike
    -isysroot this is also right when the compiler is an xcrun shim."""
    if sys.platform != "darwin" or env.get("SDKROOT"):
        return env
    try:
        path = subprocess.run(["xcrun", "--show-sdk-path"], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return env
    if path:
        env = dict(env)
        env["SDKROOT"] = path
    return env


def write_container(path: Path, images: list[tuple[str, bytes]]) -> None:
    """Device-code container read by runtime/cudart/fatbin.c:
    "OCUFAT1\\0", count, header size, then per image a 16-byte backend
    name with offset and size (little-endian), then the images."""
    import struct
    header = 16 + 32 * len(images)
    out = bytearray(b"OCUFAT1\0" + struct.pack("<II", len(images), header))
    offset = header
    for name, data in images:
        out += name.encode().ljust(16, b"\0")[:16] + struct.pack("<QQ", offset, len(data))
        offset += len(data)
    for _, data in images:
        out += data
    path.write_bytes(bytes(out))


