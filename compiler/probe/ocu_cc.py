def normalized_copies(src: Path, dest: Path):
    """If the source or a file it includes with quotes (found next to the
    including file, under the source's folder) has spaced launch chevrons,
    copy them under `dest` with the same relative layout, chevrons fixed and
    a #line marker naming the original; return the copied source, else
    None. Files outside the source's folder are left alone."""
    import re
    from cpu_rewrite import normalize_chevrons
    root = src.parent.resolve()
    pattern = re.compile(r'^[ \t]*#[ \t]*include[ \t]*"([^"]+)"', re.M)
    seen, todo, files = set(), [src.resolve()], []
    while todo:
        f = todo.pop()
        if f in seen or not f.is_file():
            continue
        seen.add(f)
        try:
            f.relative_to(root)
        except ValueError:
            continue
        text = f.read_text(encoding="utf-8", errors="surrogateescape")
        files.append((f, text))
        for name in pattern.findall(text):
            todo.append((f.parent / name).resolve())
    from cpu_rewrite import RewriteError as _RewriteError
    fixed = {}
    for f, t in files:
        try:
            fixed[f] = normalize_chevrons(t)
        except _RewriteError:
            fixed[f] = (t, 0)  # leave it to the compiler to report
    if not any(n for _, n in fixed.values()):
        return None
    for f, (text, _) in fixed.items():
        out = dest / f.relative_to(root)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(f'#line 1 "{f}"\n' + text, encoding="utf-8", errors="surrogateescape")
    return dest / src.resolve().relative_to(root)


def header_dirs() -> list[Path]:
    """Our headers: one folder in an installed package (<prefix>/include/ocu
    next to <prefix>/libexec/ocu/ocu_cc.py), three in the source tree. The
    first holds cuda_runtime.h."""
    installed = HERE.parent.parent / "include" / "ocu"
    if (installed / "cuda_runtime.h").is_file() and not (REPO / "runtime" / "include").is_dir():
        return [installed]
    return [REPO / "runtime" / "include", REPO / "backends" / "interface",
            REPO / "backends" / "cpu"]


# Clang's CUDA default (-ffp-contract=fast) fuses a*b+c into fma everywhere,
# like nvcc, but ignores "#pragma clang fp contract(off)". The device math
# library needs that pragma (its float functions round each operation as
# written, so device and host give the same bits); fast-honor-pragmas keeps
# fusion for all other code.
FP_CONTRACT = ["-ffp-contract=fast-honor-pragmas"]


def ptx_shift_step(args, src: Path, work: Path, common: list[str], side: str):
    """--ptx-shift (ptx_shift.py): a step that writes rewritten copies of
    the source and its local includes, the source to compile instead, and
    the extra compiler options (the helpers, the original folder for
    quoted includes). Without the option: nothing, src, nothing."""
    if not args.ptx_shift:
        return [], src, []
    dirs = header_dirs()
    path = pinned_cuda_path(work.parent if args.cache is None else Path(args.cache))
    ast = [_llvm_tool("clang++"), "-x", "cuda", "-std=c++17", "-nocudainc", "-nocudalib",
           f"--cuda-path={path}", f"--cuda-gpu-arch={args.arch or 'sm_80'}", side,
           *[f"-I{d}" for d in dirs], "-include", str(dirs[0] / "cuda_runtime.h"),
           "-Wno-unknown-cuda-version", *common]
    if args.target == "cpu":
        # Headers the CPU compiler finds in its own folder (omp.h with GCC)
        # come after Clang's own, so that both read the same program.
        try:
            own = subprocess.run([os.environ.get("CXX", "c++"), "-print-file-name=include"],
                                 capture_output=True, text=True).stdout.strip()
        except OSError:
            own = ""
        if own and os.path.isabs(own) and os.path.isdir(own):
            ast += ["-idirafter", own]
    dest = work / "ptx-shift"
    step = ["<ptx-shift>", str(src), str(dest), str(path), *ast]
    extra = ["-include", str(dirs[0] / "ocu_ptx_shift.h"), "-iquote", str(src.parent)]
    return [step], dest / src.name, extra


def build_commands(args, src: Path, out: Path, work: Path) -> list[list[str]]:
    codegen = []  # options that matter after preprocessing
    if args.O:
        codegen.append(f"-O{args.O}")
    if args.g:
        codegen.append("-g")
    common = list(codegen)
    for inc in args.I:
        common += ["-I", inc]
    for d in args.D:
        common += ["-D", d]
    common.append(f"-I{HERE}")

    if args.target == "cpu":
        cxx = os.environ.get("CXX", "c++")
        dirs = header_dirs()
        rt = dirs[0]
        ours = [f"-I{d}" for d in dirs]
        if src.suffix in (".c",):
            cc = os.environ.get("CC", "cc")
            return [[cc, *ours, *common, "-c", str(src), "-o", str(out)]]
        if src.suffix in (".cpp", ".cc", ".cxx", ".C"):
            return [[cxx, *ours, *common, "-c", str(src), "-o", str(out)]]
        pre = work / (src.stem + ".ii")
        rewritten = work / (src.stem + ".ocu.ii")
        shift, src, extra = ptx_shift_step(args, src, work, common, "--cuda-host-only")
        return [*shift,
                [cxx, "-std=c++17", "-x", "c++", "-E", "-DOCU_CPU_PATH",
                 "-DOCU_CPU_PREPROCESS", "-D__CUDACC__", *ours,
                 # nvcc includes cuda_runtime.h in every .cu file
                 "-include", str(rt / "cuda_runtime.h"), *extra,
                 *common, str(src), "-o", str(pre)],
                ["<rewrite>", str(pre), str(rewritten)],
                [cxx, "-std=c++17", "-x", "c++-cpp-output", *codegen,
                 "-c", str(rewritten), "-o", str(out)]]
    clang = _llvm_tool("clang++")
    if args.target == "nvidia" and not str(out).endswith(".ptx") and src.suffix in (".c",):
        cc = os.environ.get("CC", "cc")
        return [[cc, *[f"-I{d}" for d in header_dirs()], *common, "-c", str(src), "-o", str(out)]]
    if args.target == "nvidia" and not str(out).endswith(".ptx") and src.suffix != ".cu":
        cxx = os.environ.get("CXX", "c++")
        return [[cxx, *[f"-I{d}" for d in header_dirs()], *common, "-c", str(src), "-o", str(out)]]
    if args.target == "nvidia" and not str(out).endswith(".ptx"):
        # Whole program: device code as PTX in our container, embedded in
        # the host object Clang compiles; the runtime registers it.
        arch = args.arch or "sm_80"
        path = pinned_cuda_path(work.parent if args.cache is None else Path(args.cache))
        dirs = header_dirs()
        ours = [f"-I{d}" for d in dirs]
        cuda = [clang, "-x", "cuda", "-std=c++17", "-nocudainc", "-nocudalib",
                f"--cuda-path={path}", f"--cuda-gpu-arch={arch}", *ours,
                "-include", str(dirs[0] / "cuda_runtime.h"),
                "-Wno-unknown-cuda-version", *FP_CONTRACT]
        ptx = work / (src.stem + ".ptx")
        fat = work / (src.stem + ".ocufat")
        # --ptx-shift: the device pass's view of the source decides which
        # shifts are rewritten (its copies also join spaced chevrons).
        shift, src, extra = ptx_shift_step(args, src, work, common, "--cuda-device-only")
        cuda += extra
        # Spaced chevrons ("<< <"), which Clang rejects: compile copies of
        # the source and its local quoted includes with only those
        # characters changed (see normalized_copies).
        copy = None if shift else normalized_copies(src, work / "src")
        if copy is not None:
            cuda += ["-iquote", str(src.parent), "-I", str(src.parent)]
            src = copy
        return [*shift,
                [*cuda, "--cuda-device-only", "-S", *common, str(src), "-o", str(ptx)],
                ["<container>", str(fat), "nvidia", str(ptx)],
                [*cuda, "--cuda-host-only", "-Xclang", "-fcuda-include-gpubinary",
                 "-Xclang", str(fat), *common, "-c", str(src), "-o", str(out)]]
    if args.target == "nvidia":
        arch = args.arch or "sm_80"
        path = pinned_cuda_path(work.parent if args.cache is None else Path(args.cache))
        return [[clang, "-x", "cuda", "-nocudainc", "-nocudalib", f"--cuda-path={path}",
                 f"--cuda-gpu-arch={arch}", "--cuda-device-only", "-S", *FP_CONTRACT, *common,
                 str(src), "-o", str(out)]]
    arch = args.arch or "gfx1201"
    return [[clang, "-x", "hip", "-nogpuinc", "-nogpulib", f"--offload-arch={arch}",
             "--cuda-device-only", "--no-gpu-bundle-output", "-c", *common,
             str(src), "-o", str(out)]]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="ocu_cc.py", add_help=True)
    ap.add_argument("--target", choices=("cpu", "nvidia", "amd"), required=True)
    ap.add_argument("--arch")
    ap.add_argument("-c", dest="source", required=True)
    ap.add_argument("-o", dest="output", required=True)
    ap.add_argument("-I", action="append", default=[])
    ap.add_argument("-D", action="append", default=[])
    ap.add_argument("-O", choices=("0", "1", "2", "3", "s"))
    ap.add_argument("-g", action="store_true")
    ap.add_argument("--cache", help="folder for the generated version marker")
    ap.add_argument("--print-commands", action="store_true")
    ap.add_argument("--ptx-shift", action="store_true",
                    help="shifts in device code as PTX shl/shr define them (ptx_shift.py)")
    args = ap.parse_args(argv)
    if args.ptx_shift and (args.target == "amd" or
                           (args.target == "nvidia" and args.output.endswith(".ptx"))):
        print("ocu_cc: --ptx-shift is available for --target cpu and for nvidia objects, "
              "not for this output", file=sys.stderr)
        return 2

    for inc in args.I:
        real = os.path.realpath(inc)  # symlinks resolved
        if any(m in real or m in os.path.abspath(inc) for m in VENDOR_MARKERS):
            print(f"ocu_cc: refusing vendor SDK include path {inc}", file=sys.stderr)
            return 2
    # Compilers also take include paths from the environment; drop them so
    # that the guarantee holds whatever the caller's shell has set.
    env = {k: v for k, v in os.environ.items()
           if k not in ("CPATH", "C_INCLUDE_PATH", "CPLUS_INCLUDE_PATH",
                        "OBJC_INCLUDE_PATH", "CUDA_PATH", "CUDA_HOME", "HIP_PATH")}
    env = macos_sdk_env(env)

    src = Path(args.source).resolve()
    out = Path(args.output).resolve()
    with tempfile.TemporaryDirectory(prefix="ocu-cc-") as tmp:
        work = Path(tmp) / "work"
        work.mkdir()
        commands = build_commands(args, src, out, work)
        for cmd in commands:
            if args.print_commands:
                print(" ".join(shlex.quote(c) for c in cmd))
                continue
            if cmd[0] == "<container>":
                write_container(Path(cmd[1]), [(cmd[2], Path(cmd[3]).read_bytes())])
                continue
            if cmd[0] == "<ptx-shift>":
                from ptx_shift import ShiftError, prepare
                ours = [str(REPO / "runtime"), str(REPO / "backends"), cmd[3],
                        *[str(d) for d in header_dirs()]]
                try:
                    prepare(Path(cmd[1]), Path(cmd[2]), cmd[4:], env, ours,
                            lambda m: print(f"ocu_cc: --ptx-shift: {m}", file=sys.stderr))
                except ShiftError as error:
                    print(f"{args.source}: {error}", file=sys.stderr)
                    return 1
                continue
            if cmd[0] == "<rewrite>":
                try:
                    # Bytes that are not UTF-8 (old sources) pass through unchanged.
                    text = Path(cmd[1]).read_text(encoding="utf-8", errors="surrogateescape")
                    text, _stats = rewrite(text, preprocessed=True)
                except RewriteError as error:
                    print(f"{args.source}: {error}", file=sys.stderr)
                    return 1
                Path(cmd[2]).write_text(text, encoding="utf-8", errors="surrogateescape")
                continue
            done = subprocess.run(cmd, env=env)
            if done.returncode != 0:
                return done.returncode
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
