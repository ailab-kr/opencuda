#!/usr/bin/env python3
"""ocu-cc (probe): compile one .cu file for the CPU, NVIDIA or AMD path.

PROBE ONLY (PLAN P0-W1-11): a single entry point for the experiments in
this folder, and the starting point of the build-tool work in phase 2. It
is not the nvcc-compatible driver.

    ocu_cc.py --target cpu    -c k.cu -o k.o  [-I dir] [-D NAME[=V]] [-O2] [-g]
    ocu_cc.py --target nvidia --arch sm_80   -c k.cu -o k.ptx
    ocu_cc.py --target amd    --arch gfx1201 -c k.cu -o k.co
    ocu_cc.py ... --print-commands      (show what runs, do not run)

What it guarantees on every path:
  - no vendor SDK file is read: -nocudainc -nocudalib (or -nogpuinc
    -nogpulib) always, and --cuda-path points at a folder of our own whose
    only content is a one-line version marker;
  - include paths that point into a vendor SDK are refused.

cpu:    rewrite (cpu_rewrite.py) then compile as C++17 with probe_cpu.h.
        Link the object with ocu_backend_cpu, ocu_core and
        probe_cpu_runtime.cpp.
nvidia: device code only, as PTX (-S).
amd:    device code only, as a code object.
"""

from __future__ import annotations

import argparse
import os
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
VENDOR_MARKERS = ("/usr/local/cuda", "/opt/cuda", "NVIDIA GPU Computing Toolkit",
                  "/opt/rocm/include/hip/amd_detail")  # last: HIP internals, never needed

sys.path.insert(0, str(HERE))
from cpu_rewrite import RewriteError, rewrite  # noqa: E402


def pinned_cuda_path(cache: Path) -> Path:
    """Our own folder: a one-line version marker so clang targets CUDA 12.3
    (newer launch ABI, PTX 8.3). Nothing else in it is read."""
    root = cache / "ocu-cuda-path"
    (root / "include").mkdir(parents=True, exist_ok=True)
    for sub in ("bin", "lib64"):
        (root / sub).mkdir(exist_ok=True)
    marker = root / "include" / "cuda.h"
    text = "/* version marker only, generated by ocu_cc.py */\n#define CUDA_VERSION 12030\n"
    if not marker.exists() or marker.read_text() != text:
        # Write then rename: concurrent runs never see a half-written file.
        tmp = marker.with_name(f".cuda.h.{os.getpid()}")
        tmp.write_text(text)
        os.replace(tmp, marker)
    return root


def _llvm_tool(name: str) -> str:
    for v in (20, 19, 18):
        p = Path(f"/usr/lib/llvm-{v}/bin/{name}")
        if p.exists():
            return str(p)
    return name


def build_commands(args, src: Path, out: Path, work: Path) -> list[list[str]]:
    common = []
    for inc in args.I:
        common += ["-I", inc]
    for d in args.D:
        common += ["-D", d]
    if args.O:
        common.append(f"-O{args.O}")
    if args.g:
        common.append("-g")
    common.append(f"-I{HERE}")

    if args.target == "cpu":
        rewritten = work / (src.stem + ".ocu.cpp")
        cxx = os.environ.get("CXX", "c++")
        return [["<rewrite>", str(src), str(rewritten)],
                [cxx, "-std=c++17", "-DOCU_CPU_PATH",
                 f"-I{REPO / 'backends' / 'interface'}", f"-I{REPO / 'backends' / 'cpu'}",
                 *common, "-c", str(rewritten), "-o", str(out)]]
    clang = _llvm_tool("clang++")
    if args.target == "nvidia":
        arch = args.arch or "sm_80"
        path = pinned_cuda_path(work.parent if args.cache is None else Path(args.cache))
        return [[clang, "-x", "cuda", "-nocudainc", "-nocudalib", f"--cuda-path={path}",
                 f"--cuda-gpu-arch={arch}", "--cuda-device-only", "-S", *common,
                 str(src), "-o", str(out)]]
    arch = args.arch or "gfx1201"
    return [[clang, "-x", "hip", "-nogpuinc", "-nogpulib", f"--offload-arch={arch}",
             "--cuda-device-only", "--no-gpu-bundle-output", "-c", *common,
             str(src), "-o", str(out)]]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="ocu_cc.py", add_help=True)
    ap.add_argument("--target", choices=("cpu", "nvidia", "amd"), required=True)
    ap.add_argument("--arch")
    ap.add_argument("-c", dest="source", required=True)
    ap.add_argument("-o", dest="output", required=True)
    ap.add_argument("-I", action="append", default=[])
    ap.add_argument("-D", action="append", default=[])
    ap.add_argument("-O", choices=("0", "1", "2", "3", "s"))
    ap.add_argument("-g", action="store_true")
    ap.add_argument("--cache", help="folder for the generated version marker")
    ap.add_argument("--print-commands", action="store_true")
    args = ap.parse_args(argv)

    for inc in args.I:
        real = os.path.realpath(inc)  # symlinks resolved
        if any(m in real or m in os.path.abspath(inc) for m in VENDOR_MARKERS):
            print(f"ocu_cc: refusing vendor SDK include path {inc}", file=sys.stderr)
            return 2
    # Compilers also take include paths from the environment; drop them so
    # that the guarantee holds whatever the caller's shell has set.
    env = {k: v for k, v in os.environ.items()
           if k not in ("CPATH", "C_INCLUDE_PATH", "CPLUS_INCLUDE_PATH",
                        "OBJC_INCLUDE_PATH", "CUDA_PATH", "CUDA_HOME", "HIP_PATH")}

    src = Path(args.source).resolve()
    out = Path(args.output).resolve()
    with tempfile.TemporaryDirectory(prefix="ocu-cc-") as tmp:
        work = Path(tmp) / "work"
        work.mkdir()
        commands = build_commands(args, src, out, work)
        for cmd in commands:
            if args.print_commands:
                print(" ".join(shlex.quote(c) for c in cmd))
                continue
            if cmd[0] == "<rewrite>":
                try:
                    text, _stats = rewrite(Path(cmd[1]).read_text(encoding="utf-8"))
                except RewriteError as error:
                    print(f"{cmd[1]}: {error}", file=sys.stderr)
                    return 1
                Path(cmd[2]).write_text(f'#line 1 "{cmd[1]}"\n' + text, encoding="utf-8")
                continue
            done = subprocess.run(cmd, env=env)
            if done.returncode != 0:
                return done.returncode
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
